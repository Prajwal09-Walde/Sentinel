import os
from typing import List, Tuple, Literal
from eval_harness.metrics import EvalResult
from eval_harness.cost_tracker import active_call_type_var

# deepeval imports
try:
    from deepeval.metrics import HallucinationMetric
    from deepeval.test_case import LLMTestCase
except ImportError:
    HallucinationMetric = None
    LLMTestCase = None

# openai import
try:
    from openai import OpenAI
except ImportError:
    OpenAI = None


def check_out_of_scope(query: str, domain_description: str) -> bool:
    """Classify whether the query is within the RAG system's declared domain.
    
    Runs BEFORE retrieval to save LLM/embedding costs on off-topic queries.
    
    Args:
        query: The user query string.
        domain_description: The description of the allowed domain.
        
    Returns:
        True if out-of-scope, False if in-scope (or if check fails/cannot run).
    """
    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key or OpenAI is None:
        # Fallback: if OpenAI is not installed or API key is missing,
        # fail-safe and assume in-scope (False) so we don't block queries.
        return False

    try:
        model = os.environ.get("GUARDRAILS_LLM_MODEL", "gpt-4o-mini")
        client = OpenAI(api_key=api_key)
        token = active_call_type_var.set("guardrail_check")
        try:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "You are an AI guardrail assistant. Your task is to classify whether a user query is "
                            f"within or outside the following declared domain:\n'{domain_description}'\n\n"
                            "Respond with exactly one of these two options: 'IN_SCOPE' or 'OUT_OF_SCOPE'. "
                            "Do not include any other words, punctuation, or formatting."
                        )
                    },
                    {
                        "role": "user",
                        "content": f"Query: {query}"
                    }
                ],
                max_tokens=5,
                temperature=0.0
            )
        finally:
            active_call_type_var.reset(token)
        classification = response.choices[0].message.content.strip().upper()
        return "OUT_OF_SCOPE" in classification
    except Exception:
        # Fail-safe: assume in-scope on exceptions
        return False


def check_hallucination(generated_answer: str, retrieved_contexts: List[str]) -> Tuple[bool, str]:
    """Check whether claims in generated_answer are supported by retrieved_contexts.
    
    Wraps DeepEval's HallucinationMetric for a simple boolean and reason output.
    
    Args:
        generated_answer: The answer generated by the LLM.
        retrieved_contexts: The context documents retrieved for generation.
        
    Returns:
        A tuple of (is_hallucinating, explanation).
    """
    if not retrieved_contexts:
        return True, "No retrieved contexts provided to verify the generated answer against."

    if HallucinationMetric is None or LLMTestCase is None:
        return True, "DeepEval libraries are not available."

    test_case = LLMTestCase(
        input="Check hallucination",
        actual_output=generated_answer,
        context=retrieved_contexts
    )

    openai_key = os.environ.get("OPENAI_API_KEY", "")
    is_key_invalid = not openai_key or "your_openai_api_key" in openai_key or "placeholder" in openai_key

    try:
        # Default hallucination threshold is 0.7 (minimum faithfulness)
        threshold = float(os.environ.get("DEEPEVAL_HALLUCINATION_THRESHOLD", "0.7"))
        metric = HallucinationMetric(threshold=threshold)
        token = active_call_type_var.set("guardrail_check")
        try:
            metric.measure(test_case)
        finally:
            active_call_type_var.reset(token)
        
        is_hallucinating = metric.score < threshold
        explanation = metric.reason or f"Hallucination score: {metric.score:.4f} (threshold: {threshold:.4f})"
        return is_hallucinating, explanation
    except Exception as e:
        is_quota_or_auth_error = "quota" in str(e).lower() or "429" in str(e) or "api_key" in str(e).lower() or "authentication" in type(e).__name__.lower() or "ratelimit" in type(e).__name__.lower()
        if is_key_invalid or is_quota_or_auth_error:
            return False, "Bypassed hallucination check: no valid API key was provided or quota exceeded."
        return True, f"Hallucination check failed due to exception: {str(e)}"


def route_response(eval_result: EvalResult) -> Literal["serve", "caveat", "escalate"]:
    """Route RAG pipeline response based on the evaluation result.
    
    Args:
        eval_result: The EvalResult containing pass/fail and disagreement flags.
        
    Returns:
        - "serve": If evaluation passed and there was no framework disagreement.
        - "caveat": If evaluation passed but Ragas and DeepEval disagreed.
        - "escalate": If evaluation failed.
    """
    if not eval_result.passed:
        return "escalate"
    if eval_result.disagreement:
        return "caveat"
    return "serve"
